import { readdirSync, readFileSync } from 'node:fs'
import { join } from 'node:path'
import { describe, expect, test } from 'vitest'
import { ROOT } from '../src/config.ts'
import { designs, runDesign } from '../src/eval/run.ts'
import { metrics } from '../src/eval/score.ts'
import { world } from './helpers.ts'

function sources(dir: string): [string, string][] {
  return readdirSync(join(ROOT, dir), { recursive: true, encoding: 'utf8' }).filter((f) => f.endsWith('.ts')).map((f) => [f, readFileSync(join(ROOT, dir, f), 'utf8')])
}

describe('invariants', () => {
  test('the truth stays in the world: the product never imports the world or the evaluation', () => {
    for (const [f, s] of sources('src/product')) expect(s, f).not.toMatch(/from ['"](\.\.\/)+(world|eval)\//)
  })
  test("the world does not read the product's settings", () => {
    for (const [f, s] of sources('src/world')) {
      expect(s, f).not.toMatch(/product\.json|designs\.json|gate\.json|service\.json/)
      expect(s, f).not.toMatch(/from ['"]\.\.\/product\//)
    }
  })
  test('the model words and reads; code decides what to ask, what to keep and what to answer', () => {
    for (const p of ['phrase', 'extract']) expect(readFileSync(join(ROOT, `prompts/${p}.md`), 'utf8')).not.toMatch(/decide (which|what) (topic|question)|choose the next/i)
    const brain = readFileSync(join(ROOT, 'src/product/interview/brain.ts'), 'utf8')
    expect(brain.match(/'interview_free'/g)?.length).toBe(1)
    expect(brain).toMatch(/if \(this\.s\.policy === 'model'\)/)
  })
  test('same luck for every design: one seed, the same company, the same answers to the same questions', () => {
    const a = world('luck')
    const b = world('luck')
    expect(a.kus).toEqual(b.kus)
    const q = { interviewId: '', turn: 1, topic: 'drying', move: 'failure' as const, text: 'x' }
    for (const w of [a, b]) w.startInterviewAs('iv', 'E3')
    expect(a.respond({ ...q, interviewId: 'iv' })).toEqual(b.respond({ ...q, interviewId: 'iv' }))
    expect(world('other').kus.map((k) => k.value)).not.toEqual(a.kus.map((k) => k.value))
  })
  test('the demo seed holds what the platform heard and kept, not the truth', () => {
    const s = readFileSync(join(ROOT, 'demo/seed.json'), 'utf8')
    expect(s).not.toMatch(/"kuId"|"tacitHere"|"wrongValue"|"gold"/)
  })
  test('generated reports: the README states the numbers in reports/dev.json', () => {
    const readme = readFileSync(join(ROOT, 'README.md'), 'utf8')
    const dev = JSON.parse(readFileSync(join(ROOT, 'reports/dev.json'), 'utf8'))
    const p = dev.designs.find((d: { name: string }) => d.name === 'platform').metrics
    expect(readme).toContain(`${(p.capturedShare * 100).toFixed(0)}%`)
    expect(readme).toContain('<!-- generated by npm run readme -->')
  })
})

test('one company end to end: gap-driven interviews capture more, and the graph answers wrong less often than transcript search', async () => {
  const d = designs()
  const platform = metrics([await runDesign('e2e', d.find((x) => x.name === 'platform')!)])
  const forms = metrics([await runDesign('e2e', d.find((x) => x.name === 'questionnaire')!)])
  expect(platform.capturedShare).toBeGreaterThan(forms.capturedShare)
  expect(platform.atRiskShare).toBeGreaterThan(forms.atRiskShare)
  expect(platform.wrong).toBeLessThan(forms.wrong)
  expect(platform.noiseClaims).toBe(0)
})
