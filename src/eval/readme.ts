const pct = (x: number, d = 0) => `${(x * 100).toFixed(d)}%`

const TYPE: Record<string, string> = { threshold: 'Settings and numbers', exception: 'Exceptions and failure cases', rule: 'Rules of thumb', rationale: 'Reasons', procedure: 'Procedures', contact: 'Who to ask' }
const MOVE: Record<string, string> = { open: 'open question', example: 'asks for an example', failure: 'asks what goes wrong', numbers: 'asks for settings', why: 'asks why', newcomer: 'asks what a newcomer must know', who: 'asks who to call', confirm: 'checks a stated value', wrap: 'closing question' }

function table(r: Report): string {
  const row = (d: Report['designs'][number]) => {
    const m: Metrics = d.metrics
    const b = (s: string) => (d.name === 'platform' ? `**${s}**` : s)
    const lo = Math.min(...d.perSeed.map((x) => x.capturedShare))
    const hi = Math.max(...d.perSeed.map((x) => x.capturedShare))
    return `| ${b(d.label)} | ${b(pct(m.capturedShare))} <sub>${pct(lo)}–${pct(hi)}</sub> | ${b(pct(m.tacitShare))} | ${b(pct(m.atRiskShare))} | ${b(m.perExpertHour.toFixed(1))} | ${b(m.expertHours.toFixed(1))} h | ${b(String(m.wrongFacts))} | ${b(pct(m.right))} | ${b(pct(m.wrong, 1))} | ${b(pct(m.honestGap))} | ${b(`${m.costPerSessionCents.toFixed(1)} ct`)} |`
  }
  return [
    '| Design | Knowledge captured <sub>(per seed)</sub> | Tacit knowledge | Critical knowledge of leaving experts | Captured per expert hour | Expert time per company | Wrong values kept as fact | Staff questions answered right | Wrong answers | Honest "not captured yet" | Model and voice cost per session |',
    '|---|--:|--:|--:|--:|--:|--:|--:|--:|--:|--:|',
    ...r.designs.map(row),
  ].join('\n')
}

